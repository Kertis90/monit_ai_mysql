"""
Поиск нужного куска в огромном логе.

Лог на 17 ГБ прочитать целиком нельзя: даже `grep` идёт по нему минутами и
упирается в таймаут, хотя записи за нужный час занимают в нём мегабайты.
Помогает то, что лог отсортирован по времени: файл можно не читать подряд,
а делить пополам, как отсортированный массив.

Работает так: берём блок в середине файла, вытаскиваем из него первую же
строку с датой и сравниваем с искомой. Дальше половина файла отбрасывается.
Семнадцать гигабайт сходятся к нужному месту примерно за семнадцать таких
проб — это пара мегабайт чтения вместо семнадцати гигабайт.

Весь поиск идёт одной командой на самом сервере: гонять пробы по одной
через SSH означало бы семнадцать сетевых задержек вместо одной.
"""
from __future__ import annotations

import shlex

# Блок пробы. Меньше — растёт риск, что внутрь не попадёт ни одной полной
# строки с датой; больше — лишнее чтение на каждой пробе.
PROBE_BLOCK = 131072

# С какого размера бинарный поиск окупается. На файле в сотню мегабайт
# обычный grep отработает быстрее, чем три десятка проб.
BISECT_MIN_BYTES = 256 * 1024 * 1024

# Сколько читаем внутри найденного периода. Если за период накопились
# гигабайты, берём последние: вывод всё равно обрезается по числу строк
# с конца, и интереснее то, что ближе к концу периода.
SLICE_WINDOW_BYTES = 192 * 1024 * 1024

# Разбор даты в строке. Форматы те же, что перечисляет log_date_patterns:
# ISO, dd.mm.yyyy и dd/mm/yyyy у приложения, «# Time: 260907» у MySQL 5.6.
# Ключ приводится к YYYYMMDD — числу, которое сравнивается как есть.
#
# Первая строка блока пропускается (NR>1): проба начинается с произвольного
# байта, и эта строка почти всегда обрезана посередине.
DATE_KEY_AWK = r"""NR>1{
  if (match($0, /[0-9][0-9][0-9][0-9]-[0-9][0-9]-[0-9][0-9]/)) {
    s=substr($0,RSTART,RLENGTH); gsub("-","",s); print s; exit }
  if (match($0, /[0-9][0-9][.\/][0-9][0-9][.\/][0-9][0-9][0-9][0-9]/)) {
    s=substr($0,RSTART,RLENGTH);
    print substr(s,7,4) substr(s,4,2) substr(s,1,2); exit }
  if (match($0, /^# Time: [0-9][0-9][0-9][0-9][0-9][0-9] /)) {
    print "20" substr($0,9,6); exit }
}"""


def date_key(moment) -> str:
    """Дата как сравнимое число: 2026-09-07 -> 20260907."""
    return moment.strftime("%Y%m%d")


def bisect_script(path: str, since_key: str, until_key: str,
                  pipeline: str, window: int = SLICE_WINDOW_BYTES) -> str:
    """Команда, которая сама найдёт нужный кусок файла и отдаст его в pipeline.

    Печатает служебную строку `##SLICE начало конец размер` — по ней видно,
    сколько файла реально просмотрено. Это попадает в отчёт: «прочитано
    48 МБ из 17 ГБ» объясняет, почему ответ пришёл быстро.

    Неудачная проба (двоичный мусор, строки без дат) поиск не ломает: она
    считается «раньше искомого», и граница просто уезжает ближе к началу
    файла — прочитаем лишнее, но нужное не потеряем.
    """
    q = shlex.quote(path)
    lines = [
        "F=" + q,
        "B=%d" % PROBE_BLOCK,
        "S=" + shlex.quote(since_key),
        "U=" + shlex.quote(until_key),
        "W=%d" % window,
        'SZ=$(stat -c %s "$F" 2>/dev/null || wc -c < "$F")',
        "NB=$((SZ / B))",
        'k() { dd if="$F" bs=$B skip=$1 count=2 2>/dev/null | awk '
        + shlex.quote(DATE_KEY_AWK) + "; }",
        # первая граница: последний блок, который заведомо раньше периода
        "lo=0; hi=$NB",
        "while [ $((hi - lo)) -gt 1 ]; do",
        "  m=$(((lo + hi) / 2)); v=$(k $m)",
        '  if [ -n "$v" ] && [ "$v" -ge "$S" ]; then hi=$m; else lo=$m; fi',
        "done",
        # вторая: первый блок, который уже позже периода
        "lo2=$lo; hi2=$NB",
        "while [ $((hi2 - lo2)) -gt 1 ]; do",
        "  m=$(((lo2 + hi2) / 2)); v=$(k $m)",
        '  if [ -n "$v" ] && [ "$v" -gt "$U" ]; then hi2=$m; else lo2=$m; fi',
        "done",
        "st=$((lo * B))",
        "en=$(((lo2 + 2) * B))",
        "if [ $en -gt $SZ ]; then en=$SZ; fi",
        "if [ $((en - st)) -gt $W ]; then st=$((en - W)); fi",
        "if [ $st -lt 0 ]; then st=0; fi",
        'echo "##SLICE $st $en $SZ"',
        'tail -c +$((st + 1)) "$F" | head -c $((en - st)) | ' + pipeline,
    ]
    return "\n".join(lines)


def take_slice_note(text: str) -> tuple:
    """Отделить служебную строку ##SLICE от вывода.

    Возвращает (пояснение или пусто, оставшийся текст).
    """
    if not text.startswith("##SLICE "):
        return "", text
    head, _, rest = text.partition("\n")
    bits = head.split()
    if len(bits) != 4:
        return "", rest
    try:
        start, end, size = (int(b) for b in bits[1:])
    except ValueError:
        return "", rest
    read = max(end - start, 0)
    if size <= 0:
        return "", rest
    return ("просмотрено %s из %s — нужный кусок найден делением файла"
            % (human_size(read), human_size(size))), rest


def human_size(value: int) -> str:
    if value >= 1073741824:
        return "%.1f ГБ" % (value / 1073741824)
    if value >= 1048576:
        return "%.0f МБ" % (value / 1048576)
    return "%.0f КБ" % (value / 1024)
